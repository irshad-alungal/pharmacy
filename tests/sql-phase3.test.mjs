import { PGlite } from '@electric-sql/pglite'; import fs from 'fs';
const db = new PGlite(); const R = '../database/';
const OWN='b4d23fd6-8245-414d-970d-2600d3331b75', INV='11111111-1111-1111-1111-111111111111', BIL='22222222-2222-2222-2222-222222222222';
await db.exec(`create schema auth; create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('app.uid',true),'')::uuid $$;
create role anon; create role authenticated; grant usage on schema public, auth to anon, authenticated;
alter default privileges in schema public grant all on tables to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;
insert into auth.users values ('${OWN}'),('${INV}'),('${BIL}');`);
const files=['schema.sql','bootstrap-admin.sql','migrations/0004_master_data.sql','migrations/0005_purchasing.sql','migrations/0006_inventory.sql'];
for (const f of files) await db.exec(fs.readFileSync(R+f,'utf8'));
for (const f of files.slice(2)) await db.exec(fs.readFileSync(R+f,'utf8')); // idempotency
await db.exec(`insert into profiles(id,staff_id,role) values('${INV}','inv1','inventory'),('${BIL}','bill1','billing')`);
let pass=0, fail=0;
const as = async u => { await db.exec('reset role'); await db.exec(`select set_config('app.uid','${u||''}',false)`); if(u) await db.exec('set role authenticated'); };
const ok = (n,c) => { c?pass++:fail++; console.log((c?'PASS':'FAIL')+'  '+n); };
const bad = async (n, sql, re) => { try { await db.query(sql); ok(n+' (expected error)',false); } catch(e){ ok(n+' -> '+e.message.slice(0,55), re.test(e.message)); } };
const q = async s => (await db.query(s)).rows;
await db.exec(`insert into medicines(name,mrp,selling_price,tax_rate,reorder_level,purchase_price) values('Amoxil',30,25,12,100,2)`);
const med=(await q(`select id from medicines`))[0].id;
await db.exec(`insert into medicine_batches(medicine_id,batch_no,expiry,qty,quarantined) values
 ('${med}','GOOD','2030-01-01',50,false),('${med}','EXP','2020-01-01',10,false),('${med}','QUAR','2030-01-01',20,false)`);
const id = async n => (await q(`select id from medicine_batches where batch_no='${n}'`))[0].id;
const [G,E,Q]=[await id('GOOD'),await id('EXP'),await id('QUAR')];
const sale=b=>`select finalize_sale(null,'[{"batch_id":"${b}","qty":1}]'::jsonb,'[{"method":"cash","amount":25}]'::jsonb,0)`;
await as(INV);
await bad('quarantine needs a reason',`select set_quarantine('${Q}',true,'')`,/reason/i);
await db.exec(`select set_quarantine('${Q}',true,'supplier recall')`);
await db.exec('reset role'); ok('quarantine flagged + audited', (await q(`select count(*)::int c from audit_logs where action='batch_quarantined'`))[0].c===1 && (await q(`select quarantined from medicine_batches where batch_no='QUAR'`))[0].quarantined===true);
await as(OWN);
await bad('expired batch cannot be sold',sale(E),/expired/i);
await bad('quarantined batch cannot be sold',sale(Q),/quarantined/i);
await db.exec(sale(G));
ok('sale of good batch -> 49 + sale_out movement', +(await q(`select qty from medicine_batches where id='${G}'`))[0].qty===49 && (await q(`select * from stock_movements where movement_type='sale_out' and qty=-1`)).length===1);
await db.exec('reset role');
await bad('DB trigger blocks expired sale line even if function bypassed',`insert into sales_items(invoice_id,medicine_id,batch_id,qty,unit_price,tax_rate,line_total) select id,'${med}','${E}',1,25,12,25 from sales_invoices limit 1`,/cannot be sold/i);
await as(INV);
await bad('adjustment needs a reason',`select adjust_stock('${G}',-1,'damage','')`,/reason/i);
await bad('damage cannot increase stock',`select adjust_stock('${G}',5,'damage','x')`,/reduce/i);
await bad('stock cannot go negative',`select adjust_stock('${G}',-500,'adjustment','x')`,/below zero/i);
await db.exec(`select adjust_stock('${G}',-3,'damage','broken strips')`);
ok('damage -3 -> 46, logged with reason', +(await q(`select qty from medicine_batches where id='${G}'`))[0].qty===46 && (await q(`select * from stock_movements where movement_type='damage' and reason='broken strips'`)).length===1);
await bad('direct batch update denied',`update medicine_batches set qty=999`,/permission denied/i);
const n=(await q(`select physical_count('[{"batch_id":"${G}","counted":44},{"batch_id":"${Q}","counted":20}]'::jsonb,'rack A count') n`))[0].n;
ok('physical count adjusts only differing batches (1)', n===1 && +(await q(`select qty from stock_movements where movement_type='physical_count'`))[0].qty===-2);
ok('low stock alert lists the medicine', (await q(`select * from low_stock()`)).length===1);
ok('inventory_batches status flags', (await q(`select status from inventory_batches() order by batch_no`)).map(r=>r.status).join()==='expired,ok,quarantined');
ok('non-admin gets no cost values', (await q(`select cost_value from inventory_batches()`)).every(r=>r.cost_value===null));
await bad('non-admin valuation denied',`select * from inventory_valuation()`,/Not authorised/i);
await bad('select * on medicines denied (purchase_price)',`select * from medicines`,/permission denied/i);
ok('explicit-column select works (what the app uses)', (await q(`select id,name,reorder_level from medicines`)).length===1);
await as(OWN);
const v=(await q(`select * from inventory_valuation()`))[0];
console.log('  actual valuation:',JSON.stringify(v));
// GOOD: 50-1 sold-3 damaged-2 counted = 44; EXP 10; QUAR 20; cost 2/unit, price 25
ok('valuation: total 148, sellable 88, expired 20, quarantined 40, retail 1100', +v.cost_total===148 && +v.cost_sellable===88 && +v.cost_expired===20 && +v.cost_quarantined===40 && +v.retail_sellable===1100);
await as(BIL);
await bad('billing cannot adjust stock',`select adjust_stock('${G}',-1,'damage','x')`,/Not authorised/i);
await bad('billing cannot quarantine',`select set_quarantine('${G}',true,'x')`,/Not authorised/i);
await as(INV); await db.exec(`select set_quarantine('${Q}',false,'recall cleared')`);
await as(OWN); await db.exec(sale(Q));
ok('released batch is sellable again', +(await q(`select qty from medicine_batches where id='${Q}'`))[0].qty===19);
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail?1:0);
